export function resolveLocaleText(key: string, locale: Locale): string { return CENTRAL_TRANSLATION_REGISTRY[key]?.[locale] ?? CENTRAL_TRANSLATION_REGISTRY[key]?.en ?? key; }
export function resolveStatusLabel(status: string, locale: Locale): string { const normalized=String(status||'').toLowerCase(); return STATUS_TRANSLATIONS[normalized as keyof typeof STATUS_TRANSLATIONS]?.[locale] ?? normalized; }
export function resolveAssetTypeLabel(type: string, locale: Locale): string { const normalized=String(type||'').toLowerCase(); return ASSET_TYPE_TRANSLATIONS[normalized as keyof typeof ASSET_TYPE_TRANSLATIONS]?.[locale] ?? type ?? 'Other'; }
export function getLocaleCoverage(locales: readonly Locale[]) { const keys=Object.keys(CENTRAL_TRANSLATION_REGISTRY); return Object.fromEntries(locales.map(locale=>[locale,{missing:keys.filter(key=>!CENTRAL_TRANSLATION_REGISTRY[key]?.[locale])}])) as Record<Locale,{missing:string[]}>; }
export function hasCompleteLocaleCoverage(locales: readonly Locale[]) { return locales.every(locale=>getLocaleCoverage([locale])[locale].missing.length===0); }
